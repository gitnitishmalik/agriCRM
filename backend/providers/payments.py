"""
Payment request providers — manual UPI, a deterministic fake gateway, and the
seam a real one plugs into.

🔴 **A payment request is not a payment.** Nothing in this module creates a
`crm.invoice_payment` row. A UPI URI is a convenience for the person paying and
carries no information about whether they paid; INVOICE.md §11.2 is explicit
that claiming otherwise is forbidden, and the status vocabulary reflects it —
`awaiting_manual_confirmation` is where a UPI request stays until a human
records a receipt or a signed webhook matches it.

🔴 **Signature verification happens over raw request bytes.** Re-serialising a
parsed body changes whitespace and key order, so a signature computed over the
re-serialised form verifies something the sender never signed. The webhook
route therefore reads `await request.body()` and passes those exact bytes here.
"""

from __future__ import annotations

import hashlib
import hmac
import json
import logging
import uuid
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from decimal import Decimal
from typing import Any, Protocol

logger = logging.getLogger("backend.payments")


class PaymentProviderError(RuntimeError):
    """A provider failed. 🔴 Never converted into a successful response."""


@dataclass(frozen=True)
class PaymentRequestResult:
    provider: str
    provider_reference: str | None
    payload_url: str | None
    qr_svg: str | None
    status: str
    expires_at: datetime | None


@dataclass(frozen=True)
class WebhookEvent:
    """A verified (or rejected) event, parsed but not yet acted on."""

    provider_event_id: str
    event_type: str | None
    signature_verified: bool
    provider_timestamp: datetime | None
    amount: Decimal | None
    currency: str | None
    reference: str | None
    raw: dict[str, Any]
    failure: str | None = None


class PaymentProvider(Protocol):
    name: str

    async def create_request(
        self,
        *,
        invoice_no: str,
        amount: Decimal,
        currency: str,
        payee_name: str,
        note: str,
        idempotency_key: str,
    ) -> PaymentRequestResult: ...

    def parse_webhook(self, body: bytes, headers: dict[str, str]) -> WebhookEvent: ...


