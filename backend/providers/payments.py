def get_provider(name: str) -> PaymentProvider:
    """
    🔴 An unknown name raises. There is no default provider — a payment route
    that silently fell back to a fake would look like it was taking money.
    """
    from backend.config import settings

    key = (name or "").lower()
    if key == "manual_upi":
        return ManualUpiProvider(settings.upi_vpa, settings.upi_payee_name)
    if key in ("fake_gateway", "fake"):
        return FakeGatewayProvider(settings.payment_webhook_secret)
    raise PaymentProviderError(
        f"'{name}' is not a payment provider this build knows. "
        f"Available: manual_upi, fake_gateway. A live gateway is enabled by "
        f"adding its class here and supplying credentials — see DEPLOYMENT.md."
    )
