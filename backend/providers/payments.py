# The deterministic fake gateway
# ---------------------------------------------------------------------------


class FakeGatewayProvider:
    """
    A gateway that behaves like a real one, offline.

    Signs with HMAC-SHA256 over the raw body plus a timestamp, exactly the
    shape Razorpay, Stripe and Cashfree all use. That similarity is the point:
    the reconciliation logic, the replay window and the idempotency behaviour
    are exercised for real, so enabling a live provider is a class swap rather
    than a rewrite of everything downstream.
    """

    name = "fake_gateway"

    def __init__(self, secret: str) -> None:
        self.secret = secret or "fake-gateway-secret"

    async def create_request(
        self,
        *,
        invoice_no: str,
        amount: Decimal,
        currency: str,
        payee_name: str,
        note: str,
        idempotency_key: str,
    ) -> PaymentRequestResult:
        # Derived from the idempotency key, so replaying a request produces the
        # same reference rather than a second one at the provider.
        reference = "fake_" + hashlib.sha256(idempotency_key.encode()).hexdigest()[:20]
        return PaymentRequestResult(
            provider=self.name,
            provider_reference=reference,
            payload_url=f"https://fake-gateway.invalid/pay/{reference}",
            qr_svg=None,
            status="pending_provider",
            expires_at=datetime.now(UTC) + timedelta(days=7),
        )

    def sign(self, body: bytes, timestamp: str) -> str:
        """Used by tests to build a valid event, and by nothing in production."""
        return hmac.new(
            self.secret.encode(), timestamp.encode() + b"." + body, hashlib.sha256
        ).hexdigest()

    def parse_webhook(self, body: bytes, headers: dict[str, str]) -> WebhookEvent:
        lower = {key.lower(): value for key, value in headers.items()}
        signature = lower.get("x-webhook-signature", "")
        timestamp = lower.get("x-webhook-timestamp", "")

        try:
            payload = json.loads(body)
        except json.JSONDecodeError:
            return WebhookEvent(
                provider_event_id=f"unparseable-{uuid.uuid4().hex}",
                event_type=None,
                signature_verified=False,
                provider_timestamp=None,
                amount=None,
                currency=None,
                reference=None,
                raw={},
                failure="body is not JSON",
            )

        expected = self.sign(body, timestamp)
        verified = bool(signature) and hmac.compare_digest(expected, signature)

        sent_at = None
        if timestamp.isdigit():
            sent_at = datetime.fromtimestamp(int(timestamp), tz=UTC)

        amount = payload.get("amount")
        return WebhookEvent(
            # 🔴 An event with no id gets a synthetic one so the row can still
            # be stored. Storing it is what makes the rejection reviewable.
            provider_event_id=str(payload.get("event_id") or f"missing-{uuid.uuid4().hex}"),
            event_type=payload.get("event"),
            signature_verified=verified,
            provider_timestamp=sent_at,
            amount=Decimal(str(amount)) if amount is not None else None,
            currency=payload.get("currency"),
            reference=payload.get("reference"),
            raw=payload,
            failure=None if verified else "signature mismatch",
        )


