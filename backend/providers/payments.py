# Manual UPI
# ---------------------------------------------------------------------------


def _upi_uri(*, vpa: str, payee: str, amount: Decimal, note: str, ref: str) -> str:
    """
    A UPI deep link, per the NPCI parameter set.

    `am` is fixed and `cu` is INR. The transaction note carries the invoice
    number so the receipt a customer sends back can be matched to a document
    by a person reading it.
    """
    from urllib.parse import quote

    params = {
        "pa": vpa,
        "pn": payee,
        "am": f"{amount:.2f}",
        "cu": "INR",
        "tn": note[:50],
        "tr": ref[:35],
    }
    query = "&".join(f"{key}={quote(str(value), safe='')}" for key, value in params.items())
    return f"upi://pay?{query}"


def _qr_svg(payload: str, *, size: int = 240) -> str:
    """
    A QR code as inline SVG, with no dependency.

    🔴 Rendered rather than fetched. A QR generated by an image API would send
    a payment URI containing the company's VPA and an invoice amount to a third
    party on every page view, and the artifact people photograph should not
    depend on somebody else's uptime.
    """
    modules = _qr_modules(payload)
    count = len(modules)
    scale = max(1, size // (count + 8))
    quiet = 4 * scale
    dimension = count * scale + 2 * quiet

    rects = []
    for y, row in enumerate(modules):
        run_start = None
        for x in range(count + 1):
            dark = x < count and row[x]
            if dark and run_start is None:
                run_start = x
            elif not dark and run_start is not None:
                rects.append(
                    f'<rect x="{quiet + run_start * scale}" y="{quiet + y * scale}" '
                    f'width="{(x - run_start) * scale}" height="{scale}"/>'
                )
                run_start = None

    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{dimension}" '
        f'height="{dimension}" viewBox="0 0 {dimension} {dimension}" '
        f'role="img" aria-label="UPI payment QR code">'
        f'<rect width="{dimension}" height="{dimension}" fill="#ffffff"/>'
        f'<g fill="#000000">{"".join(rects)}</g></svg>'
    )


def _qr_modules(payload: str) -> list[list[bool]]:
    """
    Encode `payload` as a QR matrix.

    Uses `segno` when it is installed and raises a clear error otherwise. The
    alternative — hand-rolling Reed-Solomon here — is several hundred lines
    whose bugs would produce a QR code that scans to the wrong amount, which is
    the worst failure available in this file.
    """
    try:
        import segno
    except ImportError as error:
        raise PaymentProviderError(
            "QR rendering needs `segno` (pip install segno). The UPI link "
            "itself works without it — the request is created with a payload "
            "URL and no QR image."
        ) from error

    qr = segno.make(payload, error="m")
    return [[bool(cell) for cell in row] for row in qr.matrix]


class ManualUpiProvider:
    """
    A UPI link and QR the customer pays with, out of band.

    🔴 The resulting request is `awaiting_manual_confirmation` and stays there.
    Generating it, showing it, or watching somebody scan it records nothing —
    only a human-entered receipt creates a payment.
    """

    name = "manual_upi"

    def __init__(self, vpa: str, payee_name: str) -> None:
        if not vpa:
            raise PaymentProviderError(
                "Manual UPI is not configured: set UPI_VPA (and UPI_PAYEE_NAME) "
                "in the environment. A link to an empty VPA would be a link to "
                "nowhere printed on an invoice."
            )
        self.vpa = vpa
        self.payee_name = payee_name or "Theta"

    async def create_request(
        self,
        *,
        invoice_no: str,
        amount: Decimal,
        currency: str,
        payee_name: str,
        note: str,
        idempotency_key: str,
    ) -> PaymentRequestResult:
        if currency != "INR":
            raise PaymentProviderError("UPI settles in INR only.")

        reference = invoice_no.replace("/", "-")
        uri = _upi_uri(
            vpa=self.vpa,
            payee=payee_name or self.payee_name,
            amount=amount,
            note=note or f"Invoice {invoice_no}",
            ref=reference,
        )
        try:
            qr = _qr_svg(uri)
        except PaymentProviderError as error:
            logger.warning("UPI QR not rendered: %s", error)
            qr = None

        return PaymentRequestResult(
            provider=self.name,
            provider_reference=reference,
            payload_url=uri,
            qr_svg=qr,
            # 🔴 The whole point of this status.
            status="awaiting_manual_confirmation",
            expires_at=None,
        )

    def parse_webhook(self, body: bytes, headers: dict[str, str]) -> WebhookEvent:
        raise PaymentProviderError(
            "Manual UPI has no webhook. A UPI payment is confirmed by a person "
            "entering the receipt."
        )


